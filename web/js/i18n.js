export function t(locale, path, vars = {}) {
  const table = dict[locale] || dict.zh;
  const value = path.split('.').reduce((obj, key) => obj?.[key], table);
  const fallback = path.split('.').reduce((obj, key) => obj?.[key], dict.zh);
  let out = value ?? fallback ?? path;
  if (Array.isArray(out)) return out;
  return String(out).replace(/\{(\w+)\}/g, (_, key) => vars[key] ?? '');
}
